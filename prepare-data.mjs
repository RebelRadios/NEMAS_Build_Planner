import fs from 'node:fs';
const data=JSON.parse(fs.readFileSync('../tmp/pdfs/data.json','utf8'));
const layout=JSON.parse(fs.readFileSync('../tmp/pdfs/layout.json','utf8'));
const racial=JSON.parse(fs.readFileSync('race-attributes.json','utf8').replace(/^\uFEFF/,''));
const matched=new Set();
const normalizeName=s=>s.replace(/[\u2013\u2014]/g,'-');
for(const race of data.races){
 const tableName=race.id==='R14'?'Khajiit - first entry':race.id==='R15'?'Khajiit - second entry':race.name;
 const shared=racial.rows.find(r=>normalizeName(r.name)===tableName);
 const male=shared||racial.rows.find(r=>normalizeName(r.name)===tableName+' (M)');
 const female=shared||racial.rows.find(r=>normalizeName(r.name)===tableName+' (F)');
 if(!male||!female)throw new Error('Missing racial baseline: '+race.name);
 for(const row of [male,female]){if(row.values.length!==8||row.values.some(v=>!Number.isFinite(v))||row.values.reduce((a,b)=>a+b,0)!==310)throw new Error('Invalid racial baseline: '+row.name);matched.add(row.name);}
 race.baseAttributes=Object.fromEntries([['male',male],['female',female]].map(([sex,row])=>[sex,Object.fromEntries(racial.attributeOrder.map((k,i)=>[k,row.values[i]]))]));
 race.attributeSource={document:racial.document,status:racial.status,code:male.source,label:racial.sources[male.source]};
}
if(matched.size!==racial.rows.length)throw new Error('Unmapped racial attribute rows.');
for(const list of Object.values(data))for(const record of list)record.page=layout.entries[record.id]?.page;
fs.writeFileSync('dist/data.js',`/* Audited compendium data; regenerated by prepare-data.mjs. */\nwindow.NEMAS_DATA = ${JSON.stringify(data,null,2)};\n`);
fs.copyFileSync('../output/pdf/NEMAS_Morrowind_Character_Compendium.pdf','dist/compendium.pdf');
console.log(Object.fromEntries(Object.entries(data).map(([k,v])=>[k,v.length])));
